/** No category may take more than this many seats in a single mission. */
const MAX_PER_CATEGORY = 3;

/**
 * Picks `count` questions that have not been asked yet in this game, spread across categories,
 * with the options shuffled. When the bank runs low it starts over, so a long game never stalls.
 */
export function drawQuestions(
  rng: Rng,
  used: readonly number[],
  count: number,
): { questions: Question[]; used: number[] } {
  let seen = new Set(used);
  let pool = QUESTION_BANK.map((_, i) => i).filter((i) => !seen.has(i));
  if (pool.length < count) {
    seen = new Set();
    pool = QUESTION_BANK.map((_, i) => i);
  }
  const shuffled = rng.shuffle(pool);
  const perCategory = new Map<Category, number>();
  const picked: number[] = [];
  for (const i of shuffled) {
    const cat = (QUESTION_BANK[i] as BankQuestion).category;
    if ((perCategory.get(cat) ?? 0) >= MAX_PER_CATEGORY) continue;
    perCategory.set(cat, (perCategory.get(cat) ?? 0) + 1);
    picked.push(i);
    if (picked.length === count) break;
  }
  for (const i of shuffled) {
    if (picked.length >= count) break;
    if (!picked.includes(i)) picked.push(i);
  }
  const questions = picked.map((i) => {
    const b = QUESTION_BANK[i] as BankQuestion;
    const options = rng.shuffle([b.answer, ...b.wrong]);
    return { text: b.text, options, correct: options.indexOf(b.answer) };
  });
  return { questions, used: [...seen, ...picked] };
}
