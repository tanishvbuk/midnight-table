import type { Question } from './types';

/** [question, correct answer, three wrong answers] */
type Row = [text: string, right: string, ...wrong: [string, string, string]];

/**
 * Where the right answer sits in the four options, cycled so no position is more likely than any
 * other. The order is fixed, not random, so the bank is the same on every server and replay.
 */
const SLOTS = [2, 0, 3, 1, 1, 3, 0, 2] as const;

function build(rows: Row[]): Question[] {
  return rows.map(([text, right, ...wrong], i) => {
    const at = SLOTS[i % SLOTS.length] as number;
    const options = [...wrong];
    options.splice(at, 0, right);
    return { text, options, correct: at };
  });
}

